<?php
/**
 * 4R BET | tools/install.php  (CLI only)
 * ------------------------------------------------------------------
 * Ek hi jagah se: data dir banao, admin banao, self-test chalao.
 *
 *   php tools/install.php --email=4r@admin.com --password="StrongPass123"
 *   php tools/install.php --selftest
 *   php tools/install.php --reset-key
 *   php tools/install.php --status
 *
 * Wasmer Edge par (agar SSH capability on ho):
 *   wasmer app ssh -- wasmer run php/php:php /app/tools/install.php --selftest
 * Warna pehla /api/admin/login call hi admin bana deta hai.
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    header('Content-Type: text/plain; charset=utf-8');
    echo "not found\n";
    exit;
}

require_once __DIR__ . '/../src/JsonStore.php';
require_once __DIR__ . '/../src/Http.php';
require_once __DIR__ . '/../src/Auth.php';
require_once __DIR__ . '/../src/Repo.php';
require_once __DIR__ . '/../src/Telegram.php';

/* ---------- args ---------- */
$args = array();
foreach (array_slice($argv, 1) as $a) {
    if (strpos($a, '--') === 0) {
        $kv = explode('=', substr($a, 2), 2);
        $args[$kv[0]] = isset($kv[1]) ? $kv[1] : true;
    }
}

function line($s = '')
{
    echo $s, "\n";
}

function okf($label, $cond, $extra = '')
{
    line(($cond ? '  [ OK ] ' : '  [FAIL] ') . $label . ($extra !== '' ? '  -> ' . $extra : ''));
    return (bool) $cond;
}

$pass = 0;
$fail = 0;
function check($label, $cond, $extra = '')
{
    global $pass, $fail;
    if (okf($label, $cond, $extra)) {
        $pass++;
    } else {
        $fail++;
    }
    return (bool) $cond;
}

$store = new JsonStore();
$auth  = new Auth($store);
$repo  = new Repo($store);
$tg    = new Telegram($store, $repo);

line('');
line('4R BET API installer');
line('  data dir : ' . $store->dir());
line('  writable : ' . ($store->isWritable() ? 'yes' : 'NO'));
line('  env      : ' . (getenv('APP_ENV') ?: '(unset)'));
line('  php      : ' . PHP_VERSION . ' / ' . PHP_SAPI);
line('');

/* ==================================================================
   --status
   ================================================================== */
if (isset($args['status'])) {
    $stats = $repo->complaintStats();
    $chats = $repo->listChats(false, 100000);
    $disk  = $store->diskUsage();

    line('STATUS');
    line('  admins        : ' . $auth->adminCount());
    line('  complaints    : ' . $stats['total'] . '  (pending ' . $stats['pending']
        . ', previewing ' . $stats['previewing'] . ', successful ' . $stats['successful']
        . ', today ' . $stats['today'] . ')');
    line('  chats         : ' . $chats['total'] . '  (unread ' . $chats['unread'] . ')');
    line('  uploads       : ' . $disk['uploads']['files'] . ' files, ' . $disk['uploads']['mb'] . ' MB');
    line('  telegram      : ' . ($tg->enabled() ? 'ON' : 'off') . '  queue ' . $tg->status()['queueLen']);
    line('  appKey        : ' . ($auth->keyAutoGenerated ? 'AUTO-GENERATED (secret set karein!)' : 'from APP_KEY'));
    line('');
    exit;
}

/* ==================================================================
   --reset-key
   ================================================================== */
if (isset($args['reset-key'])) {
    $key = bin2hex(random_bytes(32));
    $store->transaction('meta.json', function ($m) use ($key) {
        if (!is_array($m)) {
            $m = array('schema' => 1, 'counters' => array());
        }
        $m['appKey'] = $key;
        $m['appKeyAutoGenerated'] = false;
        return $m;
    }, array());

    line('APP_KEY reset ho gaya (purane tokens ab invalid).');
    line('  Isse Wasmer secret me bhi daalein:');
    line('    wasmer app secrets create APP_KEY ' . $key);
    line('');
    exit;
}

/* ==================================================================
   admin create
   ================================================================== */
if (isset($args['email'])) {
    $email = (string) $args['email'];
    $pw    = isset($args['password']) ? (string) $args['password'] : '';
    $name  = isset($args['name']) ? (string) $args['name'] : 'Admin';

    if ($pw === '') {
        $pw = getenv('ADMIN_PASSWORD') ?: '';
    }
    if ($pw === '') {
        line('  [FAIL] password nahi mila: --password=... ya ADMIN_PASSWORD env');
        exit(1);
    }

    $r = $auth->upsertAdmin($email, $pw, $name);
    if (empty($r['ok'])) {
        line('  [FAIL] ' . $r['error']);
        exit(1);
    }

    line('  [ OK ] admin ' . ($r['created'] ? 'ban gaya' : 'update hua') . ': ' . $r['email']);
    line('');
    line('  Ab frontend se login karein (POST /api/admin/login).');
    line('');
}

/* ==================================================================
   --selftest
   ================================================================== */
if (isset($args['selftest'])) {
    line('SELF-TEST');

    if (!check('data dir writable', $store->isWritable(), $store->dir())) {
        line('');
        line('  Volume mount check karein: app.yaml -> volumes: [{name: 4rbet-data, mount: /data}]');
        line('  Aur DATA_DIR usi mount ke andar ho (/data/...).');
        exit(1);
    }

    /* --- JsonStore basics --- */
    $probe = 'tmp/_probe.json';
    $store->write($probe, array('hello' => 'world', 'n' => 1));
    $back = $store->read($probe, null);
    check('write + read', is_array($back) && $back['hello'] === 'world');

    $store->write($probe, array('hello' => 'world', 'n' => 2));
    $back = $store->read($probe, null);
    check('overwrite', is_array($back) && $back['n'] === 2);
    @unlink($store->path($probe));
    @unlink($store->path($probe . '.bak'));

    $n1 = $store->nextCounter('selftest');
    $n2 = $store->nextCounter('selftest');
    check('counter increment', $n2 === $n1 + 1, "$n1 -> $n2");

    check('path traversal guard', $store->safe('../../etc/passwd') === '');

    /* --- complaints --- */
    $rec = $repo->createComplaint('Selftest', array(
        'userName' => 'Self Test',
        'mobile'   => '9999900000',
        'email'    => 'selftest@example.com',
        'password' => 'Secret@123',
        'problem'  => 'Deposit nahi aaya',
        'amount'   => '500',
    ), array(), 'selftest-device', '');

    check('complaint create', is_array($rec) && !empty($rec['id']), $rec['id']);

    $got = $repo->getComplaint($rec['id']);
    check('complaint get', is_array($got) && $got['id'] === $rec['id']);

    $mine = $repo->listComplaints(array('deviceId' => 'selftest-device'), true, 10);
    check('complaint list by device', $mine['total'] >= 1);

    $masked = false;
    foreach ($mine['items'] as $it) {
        if ($it['id'] === $rec['id'] && isset($it['data']['password'])) {
            $masked = strpos($it['data']['password'], '*') !== false;
        }
    }
    check('secret field masked in list', $masked);

    $upd = $repo->setComplaintStatus($rec['id'], 'successful', 'selftest');
    check('complaint status update', $upd['status'] === 'successful');

    /* --- chats --- */
    $c = $repo->ensureChat('Self Test', '', 'selftest-device');
    $cid = $c['chat']['id'];
    check('chat ensure', !empty($cid), $cid);

    $m1 = $repo->appendMessage($cid, 'user', array('text' => 'hello admin'));
    $m2 = $repo->appendMessage($cid, 'admin', array('text' => 'hello user'));
    check('message append (user)', $m1['seq'] === 1, 'seq ' . $m1['seq']);
    check('message append (admin)', $m2['seq'] === 2, 'seq ' . $m2['seq']);

    $since0 = $repo->messagesSince($cid, 0);
    check('messages full read', count($since0['items']) === 2);

    $since1 = $repo->messagesSince($cid, 1);
    check('cursor poll (since=1)', count($since1['items']) === 1 && $since1['items'][0]['who'] === 'admin');

    $chatDoc = $repo->getChat($cid);
    check('unread counters', (int) $chatDoc['unreadAdmin'] === 1 && (int) $chatDoc['unreadUser'] === 1,
        'admin ' . $chatDoc['unreadAdmin'] . ' / user ' . $chatDoc['unreadUser']);

    $repo->markRead($cid, 'admin');
    $chatDoc = $repo->getChat($cid);
    check('markRead(admin)', (int) $chatDoc['unreadAdmin'] === 0);

    $repo->editMessage($cid, $m1['id'], 'hello admin (edited)', 'user');
    $msgs = $repo->messagesSince($cid, 0);
    $edited = false;
    foreach ($msgs['items'] as $it) {
        if ($it['id'] === $m1['id'] && strpos($it['text'], 'edited') !== false) {
            $edited = true;
        }
    }
    check('message edit', $edited);

    /* dusra user admin ka message delete na kar paye */
    $denied = false;
    try {
        $repo->deleteMessage($cid, $m2['id'], 'user', false);
    } catch (ApiError $e) {
        $denied = $e->getStatus() === 403;
    }
    check('cross-role delete blocked (403)', $denied);

    $repo->deleteMessage($cid, $m2['id'], 'admin', true);
    $msgs = $repo->messagesSince($cid, 0);
    check('admin delete works', count($msgs['items']) === 1);

    $list = $repo->listChats(false, 100);
    check('chat index list', $list['total'] >= 1);

    /* --- settings --- */
    $repo->saveSettings(array('ui' => array('showPassword' => true)), 'selftest');
    $st = $repo->getSettings();
    check('settings save/read', $st['ui']['showPassword'] === true);
    $repo->saveSettings(array('ui' => array('showPassword' => false)), 'selftest');

    /* --- auth --- */
    $tok = $auth->issue('selftest@example.com', 'admin', 60);
    check('token issue+verify (unknown admin rejected)', $auth->verify($tok['token']) === null);

    if ($auth->adminCount() === 0) {
        $auth->upsertAdmin('selftest@example.com', 'SelfTest@12345', 'Selftest');
    }
    $login = $auth->login('selftest@example.com', 'SelfTest@12345', '127.0.0.1');
    check('login', !empty($login['ok']), isset($login['error']) ? $login['error'] : '');
    if (!empty($login['ok'])) {
        check('token verify', $auth->verify($login['token']) !== null);
    }

    $bad = $auth->login('selftest@example.com', 'wrong-password', '127.0.0.2');
    check('wrong password rejected', empty($bad['ok']));

    /* --- telegram --- */
    $tst = $tg->status();
    check('telegram status readable', is_array($tst) && isset($tst['enabled']),
        $tst['enabled'] ? 'ON' : 'off (settings se on karein)');

    /* --- format sanity --- */
    $txt = Telegram::formatComplaint($rec);
    check('telegram text format', strpos($txt, 'New Complaint') === 0 && strpos($txt, $rec['id']) !== false);

    /* --- cleanup --- */
    $repo->deleteComplaint($rec['id']);
    $repo->deleteChat($cid);
    check('cleanup: complaint deleted', $repo->getComplaint($rec['id']) === null);
    check('cleanup: chat deleted', $repo->getChat($cid) === null);
    @unlink($store->path('tmp/_probe.json'));

    /* selftest admin hata do (agar humne banaya tha) */
    $store->transaction('admins.json', function ($d) {
        if (is_array($d) && isset($d['admins']) && is_array($d['admins'])) {
            $keep = array();
            foreach ($d['admins'] as $a) {
                if (isset($a['email']) && $a['email'] === 'selftest@example.com') {
                    continue;
                }
                $keep[] = $a;
            }
            $d['admins'] = $keep;
        }
        return $d;
    }, array('admins' => array()));

    line('');
    line('RESULT: ' . $pass . ' pass, ' . $fail . ' fail');
    line('');
    exit($fail === 0 ? 0 : 1);
}

/* ==================================================================
   default: help
   ================================================================== */
if (!isset($args['email'])) {
    line('Usage:');
    line('  php tools/install.php --email=4r@admin.com --password="..." [--name=Admin]');
    line('  php tools/install.php --selftest');
    line('  php tools/install.php --status');
    line('  php tools/install.php --reset-key');
    line('');
}
