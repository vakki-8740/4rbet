<?php
/**
 * 4R BET | Auth.php
 * ------------------------------------------------------------------
 * Admin authentication - ab PHP me, Firebase se koi lena-dena nahi.
 *
 * - Password: password_hash() bcrypt, admins.json (volume) me
 * - Token   : HMAC-SHA256 signed compact token (JWT jaisa, dependency-free)
 *             base64url(payload) . "." . base64url(hmac)
 * - Key     : APP_KEY env (Wasmer secret). Na mile to meta.json me
 *             auto-generate (dev convenience) + health me warning.
 * - Rate    : login par per-IP brute force limit
 *
 * Purane setup ka sabse bada hole yahi tha: panel sirf "koi login hai"
 * check karta tha, aur galat password par account auto-create ho jaata
 * tha. Yahan signup endpoint hi nahi hai - admin sirf install.php ya
 * CLI se banta hai.
 */

declare(strict_types=1);

final class Auth
{
    const FILE       = 'admins.json';
    const RL_FILE    = 'ratelimit.json';
    const TOKEN_TTL  = 604800;      /* 7 din */
    const MAX_TRIES  = 8;           /* per window */
    const WINDOW_SEC = 900;         /* 15 min */

    /** @var JsonStore */
    private $store;
    /** @var string */
    private $key;
    /** @var bool */
    public $keyAutoGenerated = false;

    public function __construct(JsonStore $store)
    {
        $this->store = $store;
        $this->key   = $this->resolveKey($store);
    }

    /* ---------- key ---------- */

    private function resolveKey(JsonStore $store)
    {
        $env = getenv('APP_KEY');
        if (is_string($env) && strlen(trim($env)) >= 16) {
            return trim($env);
        }

        /* env me nahi -> meta.json me persist (warna har deploy par
           purane tokens invalid ho jaate) */
        $meta = $store->read('meta.json', array());
        if (is_array($meta) && isset($meta['appKey']) && is_string($meta['appKey']) && strlen($meta['appKey']) >= 32) {
            return $meta['appKey'];
        }

        $key = bin2hex(random_bytes(32));
        $store->transaction('meta.json', function ($m) use ($key) {
            if (!is_array($m)) {
                $m = array('schema' => 1, 'counters' => array());
            }
            $m['appKey'] = $key;
            $m['appKeyAutoGenerated'] = true;
            return $m;
        }, array());

        $this->keyAutoGenerated = true;
        error_log('[4rbet] WARNING: APP_KEY secret set nahi hai - meta.json me auto-generate kiya gaya. '
                . 'Production me: wasmer app secrets create APP_KEY <64-char-random>');

        return $key;
    }

    /* ---------- base64url ---------- */

    private static function b64($bin)
    {
        return rtrim(strtr(base64_encode($bin), '+/', '-_'), '=');
    }

    private static function unb64($s)
    {
        $s = strtr((string) $s, '-_', '+/');
        $pad = strlen($s) % 4;
        if ($pad > 0) {
            $s .= str_repeat('=', 4 - $pad);
        }
        $out = base64_decode($s, true);
        return $out === false ? '' : $out;
    }

    /* ---------- token ---------- */

    public function issue($email, $role = 'admin', $ttl = self::TOKEN_TTL)
    {
        $now = time();
        $payload = array(
            'sub'  => (string) $email,
            'role' => (string) $role,
            'iat'  => $now,
            'exp'  => $now + (int) $ttl,
            'jti'  => bin2hex(random_bytes(8)),
        );

        $head = self::b64(json_encode($payload, JSON_UNESCAPED_SLASHES));
        $sig  = self::b64(hash_hmac('sha256', $head, $this->key, true));

        return array('token' => $head . '.' . $sig, 'expiresAt' => $payload['exp'], 'payload' => $payload);
    }

    public function verify($token)
    {
        if (!is_string($token) || $token === '' || substr_count($token, '.') !== 1) {
            return null;
        }

        list($head, $sig) = explode('.', $token);

        $expect = self::b64(hash_hmac('sha256', $head, $this->key, true));
        if (!hash_equals($expect, $sig)) {
            return null;
        }

        $raw = self::unb64($head);
        if ($raw === '') {
            return null;
        }

        $payload = json_decode($raw, true);
        if (!is_array($payload) || !isset($payload['exp'], $payload['sub'])) {
            return null;
        }

        if ((int) $payload['exp'] < time()) {
            return null;
        }

        /* admin abhi bhi admins.json me hona chahiye (delete hua to token dead) */
        $email = strtolower((string) $payload['sub']);
        $rec = $this->findAdmin($email);
        if ($rec === null) {
            return null;
        }
        if (isset($rec['disabled']) && $rec['disabled'] === true) {
            return null;
        }

        $payload['role'] = isset($rec['role']) ? $rec['role'] : 'admin';
        return $payload;
    }

    /** Token verify karo, warna 401 throw. */
    public function requireAdmin(Req $req)
    {
        $p = $this->verify($req->bearer());
        if ($p === null) {
            throw new ApiError('Login zaroori hai ya session expire ho gaya', 401);
        }
        return $p;
    }

    /* ---------- admins ---------- */

    private function admins()
    {
        $d = $this->store->read(self::FILE, array('admins' => array()));
        if (!is_array($d) || !isset($d['admins']) || !is_array($d['admins'])) {
            return array();
        }
        return $d['admins'];
    }

    public function findAdmin($email)
    {
        $email = strtolower(V::email($email));
        if ($email === '') {
            return null;
        }
        foreach ($this->admins() as $a) {
            if (is_array($a) && isset($a['email']) && strtolower((string) $a['email']) === $email) {
                return $a;
            }
        }
        return null;
    }

    public function adminCount()
    {
        return count($this->admins());
    }

    /**
     * Admin banao / password reset karo.
     * @return array{ok:bool,error?:string,created?:bool,email?:string}
     */
    public function upsertAdmin($email, $password, $name = '', $role = 'admin')
    {
        $email = strtolower(V::email($email));
        if ($email === '') {
            return array('ok' => false, 'error' => 'email sahi nahi hai');
        }
        if (!is_string($password) || strlen($password) < 8) {
            return array('ok' => false, 'error' => 'password kam se kam 8 characters ka hona chahiye');
        }

        $hash = password_hash($password, PASSWORD_BCRYPT, array('cost' => 11));
        if (!is_string($hash) || $hash === '') {
            return array('ok' => false, 'error' => 'password hash nahi ban paya');
        }

        $created = false;
        $now = $this->store->now();

        $this->store->transaction(self::FILE, function ($d) use ($email, $hash, $name, $role, $now, &$created) {
            if (!is_array($d) || !isset($d['admins']) || !is_array($d['admins'])) {
                $d = array('admins' => array());
            }

            $found = false;
            foreach ($d['admins'] as $i => $a) {
                if (is_array($a) && isset($a['email']) && strtolower((string) $a['email']) === $email) {
                    $d['admins'][$i]['hash']      = $hash;
                    $d['admins'][$i]['role']      = $role;
                    $d['admins'][$i]['updatedAt'] = $now;
                    if ($name !== '') {
                        $d['admins'][$i]['name'] = V::str($name, 80);
                    }
                    $found = true;
                    break;
                }
            }

            if (!$found) {
                $created = true;
                $d['admins'][] = array(
                    'id'        => 'adm_' . substr(bin2hex(random_bytes(6)), 0, 12),
                    'email'     => $email,
                    'name'      => V::str($name, 80) !== '' ? V::str($name, 80) : 'Admin',
                    'hash'      => $hash,
                    'role'      => $role,
                    'disabled'  => false,
                    'createdAt' => $now,
                    'updatedAt' => $now,
                );
            }

            return $d;
        }, array('admins' => array()));

        return array('ok' => true, 'created' => $created, 'email' => $email);
    }

    /* ---------- login ---------- */

    /**
     * @return array{ok:bool,error?:string,token?:string,expiresAt?:int,admin?:array,created?:bool}
     */
    public function login($email, $password, $ip = '')
    {
        $email = strtolower(V::email($email));
        if ($email === '' || !is_string($password) || $password === '') {
            return array('ok' => false, 'error' => 'Email aur password daalein');
        }

        if ($this->tooManyAttempts($ip)) {
            return array('ok' => false, 'error' => 'Bahut zyada koshish - 15 minute baad try karein');
        }

        $rec = $this->findAdmin($email);

        if ($rec === null || !isset($rec['hash'])) {
            /* pehli baar install: agar koi admin hi nahi hai to ban jaye.
               Ye safe hai kyunki sirf tab hota hai jab admins.json khaali ho. */
            if ($this->adminCount() === 0) {
                $res = $this->upsertAdmin($email, $password, 'Admin');
                if (!$res['ok']) {
                    return array('ok' => false, 'error' => $res['error']);
                }
                $rec = $this->findAdmin($email);
                $this->noteAttempt($ip, true);

                $t = $this->issue($email, isset($rec['role']) ? $rec['role'] : 'admin');
                return array('ok' => true, 'created' => true) + $t + array('admin' => $this->publicAdmin($rec));
            }

            $this->noteAttempt($ip, false);
            return array('ok' => false, 'error' => 'Email ya password galat hai');
        }

        if (isset($rec['disabled']) && $rec['disabled'] === true) {
            return array('ok' => false, 'error' => 'Ye account band hai');
        }

        if (!password_verify($password, (string) $rec['hash'])) {
            $this->noteAttempt($ip, false);
            return array('ok' => false, 'error' => 'Email ya password galat hai');
        }

        if (password_needs_rehash((string) $rec['hash'], PASSWORD_BCRYPT, array('cost' => 11))) {
            $this->upsertAdmin($email, $password, isset($rec['name']) ? (string) $rec['name'] : '');
        }

        $this->noteAttempt($ip, true);

        /* lastLoginAt update (lock ke andar) */
        $now = $this->store->now();
        $this->store->transaction(self::FILE, function ($d) use ($email, $now) {
            if (is_array($d) && isset($d['admins']) && is_array($d['admins'])) {
                foreach ($d['admins'] as $i => $a) {
                    if (isset($a['email']) && strtolower((string) $a['email']) === $email) {
                        $d['admins'][$i]['lastLoginAt'] = $now;
                        break;
                    }
                }
            }
            return $d;
        }, array('admins' => array()));

        $rec = $this->findAdmin($email);
        $t = $this->issue($email, isset($rec['role']) ? $rec['role'] : 'admin');

        return array('ok' => true, 'created' => false) + $t + array('admin' => $this->publicAdmin($rec));
    }

    private function publicAdmin($rec)
    {
        if (!is_array($rec)) {
            return array();
        }
        return array(
            'id'          => isset($rec['id']) ? $rec['id'] : '',
            'email'       => isset($rec['email']) ? $rec['email'] : '',
            'name'        => isset($rec['name']) ? $rec['name'] : 'Admin',
            'role'        => isset($rec['role']) ? $rec['role'] : 'admin',
            'lastLoginAt' => isset($rec['lastLoginAt']) ? $rec['lastLoginAt'] : '',
        );
    }

    /* ---------- rate limit (login) ---------- */

    private function tooManyAttempts($ip)
    {
        if ($ip === '') {
            return false;
        }

        $d = $this->store->read(self::RL_FILE, array());
        if (!is_array($d)) {
            $d = array();
        }

        $cut = time() - self::WINDOW_SEC;
        $hits = array();
        if (isset($d[$ip]) && is_array($d[$ip])) {
            foreach ($d[$ip] as $t) {
                if ((int) $t >= $cut) {
                    $hits[] = (int) $t;
                }
            }
        }

        return count($hits) >= self::MAX_TRIES;
    }

    private function noteAttempt($ip, $success)
    {
        if ($ip === '') {
            return;
        }

        $cut = time() - self::WINDOW_SEC;
        $now = time();

        $this->store->transaction(self::RL_FILE, function ($d) use ($ip, $cut, $now, $success) {
            if (!is_array($d)) {
                $d = array();
            }

            /* purane entries saaf + map ko chhota rakho */
            if (count($d) > 500) {
                $fresh = array();
                foreach ($d as $k => $v) {
                    $keep = array();
                    if (is_array($v)) {
                        foreach ($v as $t) {
                            if ((int) $t >= $cut) {
                                $keep[] = (int) $t;
                            }
                        }
                    }
                    if ($keep) {
                        $fresh[$k] = $keep;
                    }
                }
                $d = $fresh;
            }

            $hits = array();
            if (isset($d[$ip]) && is_array($d[$ip])) {
                foreach ($d[$ip] as $t) {
                    if ((int) $t >= $cut) {
                        $hits[] = (int) $t;
                    }
                }
            }

            /* success par counter reset */
            $d[$ip] = $success ? array() : array_merge($hits, array($now));

            return $d;
        }, array());
    }
}
