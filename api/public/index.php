/* --- uploaded files (auth-free read; paths guess-proof UUID) --- */
$router->get('/api/files/{yyyy}/{mm}/{name}', function (array $p) use ($req, $resp, $repo) {
    $rel = 'uploads/' . $p['yyyy'] . '/' . $p['mm'] . '/' . $p['name'];
    $full = $repo->uploadPath($rel);

    if ($full === null) {
        return $resp->json(array('ok' => false, 'error' => 'file nahi mili'), 404);
    }

    $mime = Uploads::mimeFor(pathinfo($full, PATHINFO_EXTENSION));
    $dl   = $req->flag('download') ? basename($full) : '';

    return $resp->file($full, $mime, $dl);
});

