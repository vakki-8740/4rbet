$router->post('/api/complaints', function (array $p) use ($req, $resp, $repo, $telegram, $deviceId) {
    $j = $req->json();
    if ($j === null) {
        $j = array();
    }

    $category = V::str(
        isset($j['category']) ? $j['category'] : (string) $req->field('category'),
        60
    );
    $data = isset($j['data']) && is_array($j['data']) ? $j['data'] : array();

    /* multipart se aaya ho to form field "data" JSON string hota hai */
    if (!$data) {
        $rawData = (string) $req->field('data');
        if ($rawData !== '') {
            $dec = json_decode($rawData, true);
            if (is_array($dec)) {
                $data = $dec;
            }
        }
    }

    if (!$data) {
        /* aakhri fallback: saare non-file fields = data */
        foreach ($req->fields() as $k => $v) {
            if ($k === 'category' || $k === 'deviceId' || $k === 'chatId' || $k === 'data') {
                continue;
            }
            $data[$k] = $v;
        }
    }

    /* images: multipart me image_<field> ya files[] */
    $saved = array();
    foreach ($req->files() as $name => $info) {
        if (!is_array($info)) {
            continue;
        }
        /* PHP multiple-file syntax: image_x[] */
        if (isset($info['name']) && is_array($info['name'])) {
            $count = count($info['name']);
            for ($i = 0; $i < $count; $i++) {
                $one = array(
                    'name' => $info['name'][$i], 'type' => $info['type'][$i],
                    'tmp_name' => $info['tmp_name'][$i], 'error' => $info['error'][$i],
                    'size' => $info['size'][$i],
                );
                $field = preg_replace('/^image_/', '', $name);
                $r = Uploads::save($store, $one, 'image');
                if ($r['ok']) {
                    $r['field'] = $field;
                    $saved[] = $r;
                }
            }
            continue;
        }
        $field = preg_replace('/^image_/', '', $name);
        $r = Uploads::save($store, $info, 'image');
        if ($r['ok']) {
            $r['field'] = $field;
            $saved[] = $r;
        }
    }

    $chatId = V::id(isset($j['chatId']) ? $j['chatId'] : (string) $req->field('chatId'), 40);

    $rec = $repo->createComplaint($category, $data, $saved, $deviceId($req), $chatId);

    /* server-side telegram alert */
    $tg = $telegram->notifyComplaint($rec);

    return $resp->json(array(
        'ok'       => true,
        'id'       => $rec['id'],
        'complaint'=> array(
            'id'        => $rec['id'],
            'category'  => $rec['category'],
            'status'    => $rec['status'],
            'createdAt' => $rec['createdAt'],
            'data'      => $rec['data'],
            'images'    => array_map(function ($im) { return array('id' => $im['id'], 'name' => $im['name'], 'url' => $im['url']); }, $rec['images']),
        ),
        'telegram' => array('sent' => !empty($tg['sent']), 'skipped' => !empty($tg['skipped'])),
    ), 201);
});

