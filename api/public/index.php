$router->post('/api/chats/{id}/messages', function (array $p) use ($req, $resp, $repo, $telegram) {
    $j = $req->json();
    if ($j === null) {
        $j = array();
    }

    $text = isset($j['text']) ? (string) $j['text'] : (string) $req->field('text');
    $name = isset($j['userName']) ? V::str($j['userName'], 40) : V::str((string) $req->field('userName'), 40);

    $att = null;
    $files = $req->files();
    foreach ($files as $fname => $info) {
        if (!is_array($info)) {
            continue;
        }
        if (isset($info['name']) && is_array($info['name'])) {
            $info = array(
                'name' => $info['name'][0], 'type' => $info['type'][0],
                'tmp_name' => $info['tmp_name'][0], 'error' => $info['error'][0],
                'size' => $info['size'][0],
            );
        }
        $att = Uploads::save($store, $info, 'image');
        break;
    }
    if ($att !== null && empty($att['ok'])) {
        return $resp->json(array('ok' => false, 'error' => $att['error']), 400);
    }

    $msg = array('text' => $text);
    if ($att !== null) {
        $att['field'] = 'chat';
        $msg['attachment'] = $att;
    }

    /* chat auto-create (purana behaviour: pehla message hi chat bana deta tha) */
    $chat = $repo->getChat($p['id']);
    if ($chat === null) {
        $repo->ensureChat($name, $p['id']);
    }

    $out = $repo->appendMessage($p['id'], 'user', $msg, $name);

    $telegram->notifyMessage($p['id'], 'user', $out['text'], $out['name']);

    return $resp->json(array('ok' => true, 'message' => $out), 201);
});

