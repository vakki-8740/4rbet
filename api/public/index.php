$router->get('/api/admin/complaints/{id}', function (array $p) use ($req, $resp, $auth, $repo) {
    $auth->requireAdmin($req);

    $rec = $repo->getComplaint($p['id']);
    if ($rec === null) {
        return $resp->json(array('ok' => false, 'error' => 'complaint nahi mili'), 404);
    }

    if (!$req->flag('unmasked') && isset($rec['data'])) {
        foreach ($rec['data'] as $k => $v) {
            if (in_array($k, Repo::$SECRET_FIELDS, true)) {
                $rec['data'][$k] = Repo::mask((string) $v);
            }
        }
    }

    return $resp->json(array('ok' => true, 'complaint' => $rec));
});

