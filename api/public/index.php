/* ==================================================================
   DISPATCH
   ================================================================== */

$path = $req->path();

/* root par chhota sa landing (deploy verify karne ke liye) */
if ($path === '/' || $path === '') {
    $resp->json(array(
        'ok'   => true,
        'app'  => '4rbet-api',
        'docs' => '/api/health',
        'note' => 'PHP + JSON-file backend on Wasmer Edge',
    ))->send();
    exit;
}

try {
    $result = $router->dispatch($req, $resp);

    if ($result === null) {
        /* handler ne body khud bhej di (file stream) */
        $resp->send();
        exit;
    }

    if ($result instanceof Res) {
        $result->send();
        exit;
    }

    if (is_array($result) || $result === true || $result === false) {
        $resp->json($result)->send();
        exit;
    }

    $resp->json(array('ok' => true))->send();
    exit;

} catch (ApiError $e) {
    $resp->json(array('ok' => false, 'error' => $e->getMessage(), 'code' => $e->getCode()), $e->getStatus())->send();
    exit;

} catch (Throwable $e) {
    error_log('[4rbet] ' . $e->getMessage() . ' @ ' . $e->getFile() . ':' . $e->getLine());

    $debug = $req->flag('debug') && getenv('APP_ENV') !== 'production';
    $resp->json(array(
        'ok'    => false,
        'error' => 'server error',
        'detail'=> $debug ? $e->getMessage() . ' @ ' . basename($e->getFile()) . ':' . $e->getLine() : null,
    ), 500)->send();
    exit;
}
